#!/usr/bin/env bash
# Compare the labels rush GENERATES for an external repo against the labels
# the target project DECLARES for it.
#
# rush synthesizes a BUILD file for repos that ship none (highwayhash is a
# Makefile project) or that it substitutes. When that synthesized file omits
# a label the project's own BUILD declares, the dependency resolves to
# nothing, rush stubs it empty, and the build continues - surfacing much
# later as an undefined symbol that names neither the repo nor the label.
# Two such gaps reached a passing build before this script existed:
# @highwayhash//:hh_types and @com_google_protobuf//:protobuf_lite.
#
# Run from a workspace rush has already analyzed at least once.
#
#   scripts/audit_stub_labels.sh [workspace-root]
#
# Platform-conditional labels (android, windows, apple, ios, osx) are
# reported separately: they are config_settings a Linux build never asks
# for, so they are noise rather than gaps.
set -uo pipefail
WS="${1:-$PWD}"
cd "$WS" || { echo "no such workspace: $WS" >&2; exit 2; }

EXT=".cache/rush/external"
[ -d "$EXT" ] || { echo "no $EXT - run a build here first" >&2; exit 2; }

labels() { grep -oE 'name = "[A-Za-z0-9_.-]+"' "$1" 2>/dev/null \
             | sed 's/name = //;s/"//g' | sort -u; }

gaps=0
for dir in "$EXT"/*/; do
    repo=$(basename "$dir")
    rush_build="$dir/BUILD"
    [ -f "$rush_build" ] || continue
    # Only synthesized files; a materialized upstream BUILD is not ours.
    grep -qE 'Stub BUILD|Auto-generated by Rush|Synthesized by rush|^# BUILD for' \
        "$rush_build" || continue

    declared=$(ls "third_party/$repo"/*.BUILD "third_party/$repo.BUILD" 2>/dev/null | head -1)
    [ -n "$declared" ] || continue

    missing=$(comm -13 <(labels "$rush_build") <(labels "$declared"))
    [ -n "$missing" ] || continue

    real=$(printf '%s\n' "$missing" | grep -vEi 'android|windows|apple|ios|osx' | tr '\n' ' ')
    plat=$(printf '%s\n' "$missing" | grep -Ei  'android|windows|apple|ios|osx' | tr '\n' ' ')

    if [ -n "$(echo "$real" | tr -d ' ')" ]; then
        echo "GAP      @$repo declares but rush omits: $real"
        gaps=$((gaps+1))
    fi
    [ -n "$(echo "$plat" | tr -d ' ')" ] && echo "  (platform-only, ignored: $plat)"
done

echo "--- $gaps repo(s) with non-platform label gaps ---"
[ "$gaps" -eq 0 ]

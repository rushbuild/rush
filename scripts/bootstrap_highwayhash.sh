#!/usr/bin/env bash
# Bootstrap real @highwayhash source + libhighwayhash.a from the TF-pinned archive.
#
# TensorFlow 2.15's libtensorflow_framework.so references highwayhash's
# dispatch (HighwayHash<N>::operator(), HighwayHashCat<N>::operator(),
# InstructionSets::Supported) — defined in highwayhash_target.cc (compiled once
# per SIMD target with HH_TARGET namespacing) and instruction_sets.cc. rush's
# @highwayhash adapter was header-only (clone root on -I), so those symbols were
# left undefined in the .so. This materializes the genuine pinned source and
# builds a real libhighwayhash.a using highwayhash's OWN Makefile — which does
# the per-target highwayhash_target.cc compile correctly — so NO STUBS and no
# fragile transcription of the multi-target SIMD copts.
#
# Pinned commit + URL transcribed from
# tensorflow/third_party/highwayhash/workspace.bzl.
set -euo pipefail

HH_SHA="c13d28517a4db259d738ea4886b1f00352a3cc33"
HH_URL="https://github.com/google/highwayhash/archive/${HH_SHA}.tar.gz"

CACHE="${RUSH_GLOBAL_CLONE_CACHE:-/data/rush-cache/external}"
HH_ROOT="${CACHE}/highwayhash"   # so `#include "highwayhash/sip_hash.h"` resolves with -I${HH_ROOT}

mkdir -p "$CACHE"

# --- materialize source (idempotent) ---
if [ ! -f "${HH_ROOT}/highwayhash/sip_hash.h" ]; then
    echo "highwayhash: downloading pinned ${HH_SHA} ..."
    tmp="$(mktemp -d)"
    curl -fsSL "$HH_URL" -o "${tmp}/hh.tgz"
    tar -xzf "${tmp}/hh.tgz" -C "${tmp}"
    # Preserve any rush-written BUILD stub by extracting into a fresh dir then
    # copying source over it (the BUILD is regenerated by external_deps.rs).
    cp -r "${tmp}/highwayhash-${HH_SHA}/." "$HH_ROOT/"
    rm -rf "$tmp"
fi
[ -f "${HH_ROOT}/highwayhash/sip_hash.h" ] || { echo "ERROR: highwayhash/sip_hash.h missing after materialize" >&2; exit 1; }
echo "highwayhash source: ${HH_ROOT}"

# --- build libhighwayhash.a via highwayhash's own Makefile (the real build) ---
# The Makefile target `lib/libhighwayhash.a` = SIP_OBJS + HIGHWAYHASH_OBJS +
# c_bindings.o; HIGHWAYHASH_OBJS is the per-SIMD-target highwayhash_target.cc set
# the Makefile compiles with the correct -mavx2 / -msse4.1 / portable flags.
echo "highwayhash: building lib/libhighwayhash.a (upstream Makefile) ..."
make -C "$HH_ROOT" -j"$(nproc)" lib/libhighwayhash.a CXX="${CXX:-g++}"

# Expose the archive at the clone root (where the @highwayhash adapter links it).
cp -f "${HH_ROOT}/lib/libhighwayhash.a" "${HH_ROOT}/libhighwayhash.a"
[ -f "${HH_ROOT}/libhighwayhash.a" ] || { echo "ERROR: libhighwayhash.a not produced" >&2; exit 1; }
echo "highwayhash: built ${HH_ROOT}/libhighwayhash.a ($(ar t "${HH_ROOT}/libhighwayhash.a" | wc -l) objects)"
